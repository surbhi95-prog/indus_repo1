# Customer PO (Purchase Order)
# Customer accepts quotation and sends official PO.

import uuid
from django.db import models
from apps.sales.models.customer import Customer
from apps.sales.models.quotation import Quotation
class CustomerPO(models.Model):

    class Status(models.TextChoices):
        DRAFT = "DRAFT", "Draft"
        RECEIVED = "RECEIVED", "Received"
        CONFIRMED = "CONFIRMED", "Confirmed"
        COMPLETED = "COMPLETED", "Completed"
        CANCELLED = "CANCELLED", "Cancelled"

    id = models.UUIDField(
        primary_key=True,
        default=uuid.uuid4,
        editable=False,
    )

    # Internal reference generated by our system.
    po_number = models.CharField(max_length=50, unique=True)

    # Reference supplied by the customer.
    customer_po_number = models.CharField(max_length=100)

    customer = models.ForeignKey(
        Customer,
        on_delete=models.PROTECT,
        related_name="purchase_orders",
    )

    quotation = models.ForeignKey(
        Quotation,
        on_delete=models.PROTECT,
        related_name="customer_pos",
        null=True,
        blank=True,
    )

    po_date = models.DateField()
    delivery_date = models.DateField(null=True, blank=True)

    status = models.CharField(
        max_length=20,
        choices=Status.choices,
        default=Status.DRAFT,
    )

    currency = models.CharField(max_length=3, default="INR")
    payment_terms = models.CharField(max_length=100)

    billing_address = models.TextField()
    shipping_address = models.TextField(blank=True)

    subtotal = models.DecimalField(
        max_digits=14, decimal_places=2, default=0
    )
    discount_amount = models.DecimalField(
        max_digits=14, decimal_places=2, default=0
    )
    tax_amount = models.DecimalField(
        max_digits=14, decimal_places=2, default=0
    )
    grand_total = models.DecimalField(
        max_digits=14, decimal_places=2, default=0
    )

    notes = models.TextField(blank=True)
    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

